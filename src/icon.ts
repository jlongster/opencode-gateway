export function workspace(workspaceID: string) {
  let hash = 2_166_136_261;
  for (const character of workspaceID) {
    hash ^= character.codePointAt(0) ?? 0;
    hash = Math.imul(hash, 16_777_619);
  }
  return symbols[(hash >>> 0) % symbols.length];
}
